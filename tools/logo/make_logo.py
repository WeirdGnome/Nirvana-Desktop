#!/usr/bin/env python3
"""Nirvana Desktop - the logo (an enso: a red and white brush circle on night blue) into
platinum/logo_data.h: PNG files of several sizes, built into every Nirvana program
(the menu bar, About, the login and lock screens, the screen savers).

The source is tools/logo/enso-512.png. Small sizes get a little more color - the checkered
red and white brush would otherwise melt into pink.  Needs Pillow:
    python3 tools/logo/make_logo.py
"""
import io
import os

from PIL import Image, ImageEnhance

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "enso-512.png")
OUT = os.path.join(HERE, "..", "..", "platinum", "logo_data.h")
SIZES = [16, 20, 24, 32, 48, 64, 96, 128, 256]

src = Image.open(SRC).convert("RGB")
parts = []
for s in SIZES:
    img = src if s == src.width else src.resize((s, s), Image.LANCZOS)
    if s <= 48:
        boost = 1.6 if s <= 24 else 1.3
        img = ImageEnhance.Contrast(ImageEnhance.Color(img).enhance(boost)).enhance(1.15)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    rows = []
    for i in range(0, len(data), 24):
        rows.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    parts.append((s, len(data), "\n".join(rows)))

with open(OUT, "w") as f:
    f.write("// Nirvana Desktop - the logo (an enso) as PNG files of several sizes.\n"
            "// Generated by tools/logo/make_logo.py from tools/logo/enso-512.png - do not edit.\n"
            "#pragma once\n\nnamespace plat {\nnamespace logo_data {\n\n")
    for s, n, rows in parts:
        f.write("static const unsigned char png%d[%d] = {\n%s\n};\n\n" % (s, n, rows))
    f.write("struct Png { int size; const unsigned char *data; int len; };\n")
    f.write("static const Png all[] = {\n")
    for s, n, _ in parts:
        f.write("  {%d, png%d, %d},\n" % (s, s, n))
    f.write("};\n\n}  // namespace logo_data\n}  // namespace plat\n")
print("written", OUT, sum(n for _, n, _ in parts), "bytes of PNG")
