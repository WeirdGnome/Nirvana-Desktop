#!/usr/bin/env python3
"""Nirvana Desktop - the logo (an enso: a red and white brush circle, transparent around) into
platinum/logo_data.h: PNG files of several sizes, built into every Nirvana program
(the menu bar, About, the login and lock screens, the screen savers).

The source is tools/logo/enso-512.png. Small sizes get a little more color - the checkered
red and white brush would otherwise melt into pink.  Needs Pillow:
    python3 tools/logo/make_logo.py
"""
import io
import os

from PIL import Image, ImageEnhance

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "enso-512.png")
OUT = os.path.join(HERE, "..", "..", "platinum", "logo_data.h")
SIZES = [16, 20, 24, 32, 48, 64, 96, 128, 256]

BG = (0, 42, 140)   # the night blue around the circle: made transparent


def keyed(img):
    """The blue background out: transparent, a soft edge, and no blue fringe left on the
    brush (the color without its share of blue)."""
    img = img.convert("RGB")
    out = Image.new("RGBA", img.size)
    src_px, out_px = img.load(), out.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b = src_px[x, y]
            d = abs(r - BG[0]) + abs(g - BG[1]) + abs(b - BG[2])
            a = min(1.0, max(0.0, (d - 40) / 110.0))
            if a <= 0:
                out_px[x, y] = (0, 0, 0, 0)
                continue
            # un-mix the background: c = a*fg + (1-a)*bg
            fg = [min(255, max(0, round((c - (1 - a) * k) / a))) for c, k in zip((r, g, b), BG)]
            out_px[x, y] = (fg[0], fg[1], fg[2], round(a * 255))
    return out


def resized(img, s):
    """Smaller with the colors weighed by their transparency (no dark halo)."""
    if s == img.width:
        return img
    pre = img.convert("RGBa").resize((s, s), Image.LANCZOS)
    return pre.convert("RGBA")


src = keyed(Image.open(SRC))
parts = []
for s in SIZES:
    img = resized(src, s)
    if s <= 48:
        boost = 1.6 if s <= 24 else 1.3
        a = img.getchannel("A")
        rgb = ImageEnhance.Contrast(ImageEnhance.Color(img.convert("RGB")).enhance(boost)).enhance(1.15)
        img = rgb.convert("RGBA")
        img.putalpha(a)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    rows = []
    for i in range(0, len(data), 24):
        rows.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    parts.append((s, len(data), "\n".join(rows)))

with open(OUT, "w") as f:
    f.write("// Nirvana Desktop - the logo (an enso) as PNG files of several sizes.\n"
            "// Generated by tools/logo/make_logo.py from tools/logo/enso-512.png - do not edit.\n"
            "#pragma once\n\nnamespace plat {\nnamespace logo_data {\n\n")
    for s, n, rows in parts:
        f.write("static const unsigned char png%d[%d] = {\n%s\n};\n\n" % (s, n, rows))
    f.write("struct Png { int size; const unsigned char *data; int len; };\n")
    f.write("static const Png all[] = {\n")
    for s, n, _ in parts:
        f.write("  {%d, png%d, %d},\n" % (s, s, n))
    f.write("};\n\n}  // namespace logo_data\n}  // namespace plat\n")
print("written", OUT, sum(n for _, n, _ in parts), "bytes of PNG")
